"""Publish numeric, unapproved local pose drafts; never publish review evidence."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'data/experimental-poses'
OUT.mkdir(exist_ok=True)
groups = {}
for path in sorted((ROOT / 'output/offline-pose/ready').glob('*.scene.json')):
    stem, view = path.name.removesuffix('.scene.json').rsplit('_', 1)
    scene = json.loads(path.read_text())
    assert scene['schema'] == 'pose-atlas/studio@3'
    group = groups.setdefault(stem, {'schema': 'pose-atlas/experimental-pose@1', 'id': stem,
        'status': 'experimental-unapproved', 'scene': scene, 'cameras': {}})
    assert group['scene']['figures'] == scene['figures'], f'Conflicting views: {stem}'
    group['cameras'][view] = scene['camera']
    if view == 'f': group['scene'] = scene
index = {}
for stem, data in groups.items():
    (OUT / f'{stem}.json').write_text(json.dumps(data, separators=(',', ':')) + '\n')
    index[stem] = {'views': list(data['cameras']), 'figures': len(data['scene']['figures']),
                   'view': data['scene']['reference']['view']}
(ROOT / 'studio/experimental-catalog.js').write_text('// Generated by scripts/export-experimental-poses.py. Unapproved drafts.\nexport const EXPERIMENTAL_POSES = ' + json.dumps(index, separators=(',', ':')) + ';\n')
print(f'Exported {len(index)} shared pose groups; approval state unchanged.')
